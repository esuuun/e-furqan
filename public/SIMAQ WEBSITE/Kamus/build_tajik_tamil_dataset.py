def enrich_dhamir_data():
    print("Enriching dhamir_data.json and dhamir_data.js with Tajik & Tamil...")
    with open(os.path.join(BASE_DIR, 'tg_translations.json'), 'r', encoding='utf-8') as f:
        tg_trans = json.load(f)
    with open(os.path.join(BASE_DIR, 'ta_translations.json'), 'r', encoding='utf-8') as f:
        ta_trans = json.load(f)
    with open(os.path.join(BASE_DIR, 'dhamir_data.json'), 'r', encoding='utf-8') as f:
        data = json.load(f)

    for item in data:
        b = item.get('Bentuk Kata', '')
        nk = str(item.get('No kata', ''))
        g_key = f"{b}__{nk}"
        s_num = str(item.get('SURAT', ''))
        v_key = f"{item.get('SURAT')}:{item.get('AYAT')}"

        # TG
        item['BentukKataTG'] = BENTUK_KATA_TG.get(b, b)
        item['SuratArtiTG'] = TAJIK_SURAHS.get(s_num, item.get('SuratArtiEN', ''))
        g_tg = TAJIK_GRAMMAR.get(g_key, {})
        item['ArtiKataTG'] = g_tg.get('arti_tg', item.get('ArtiKataEN', ''))
        item['TeksArtiTG'] = tg_trans.get(v_key, item.get('TeksArtiEN', ''))

        # TA
        item['BentukKataTA'] = BENTUK_KATA_TA.get(b, b)
        item['SuratArtiTA'] = TAMIL_SURAHS.get(s_num, item.get('SuratArtiEN', ''))
        g_ta = TAMIL_GRAMMAR.get(g_key, {})
        item['ArtiKataTA'] = g_ta.get('arti_ta', item.get('ArtiKataEN', ''))
        item['TeksArtiTA'] = ta_trans.get(v_key, item.get('TeksArtiEN', ''))

        # Grammar dict
        if 'Grammar' not in item or not isinstance(item['Grammar'], dict):
            item['Grammar'] = {}
        if g_tg.get('arti_tg'): item['Grammar']['arti_tg'] = g_tg['arti_tg']
        if g_tg.get('desc_tg'): item['Grammar']['desc_tg'] = g_tg['desc_tg']
        if g_tg.get('jenis_tg'): item['Grammar']['jenis_tg'] = g_tg['jenis_tg']

        if g_ta.get('arti_ta'): item['Grammar']['arti_ta'] = g_ta['arti_ta']
        if g_ta.get('desc_ta'): item['Grammar']['desc_ta'] = g_ta['desc_ta']
        if g_ta.get('jenis_ta'): item['Grammar']['jenis_ta'] = g_ta['jenis_ta']

    with open(os.path.join(BASE_DIR, 'dhamir_data.json'), 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    js_content = f"/**\n * Dataset Dhamir & Isim Jamid Mabny Al-Qur'an 35 Bahasa\n */\nconst DHAMIR_DATA = {json.dumps(data, ensure_ascii=False, indent=2)};\n"
    with open(os.path.join(BASE_DIR, 'dhamir_data.js'), 'w', encoding='utf-8') as f:
        f.write(js_content)
    print(f"  [OK] Dhamir data enriched ({len(data)} rows).")


