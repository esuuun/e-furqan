function SurahSelector({ availableSurahs, selectedSurah, onSelectSurah }) {
  // Sort numerically based on Surah ID since availableSurahs are strings
  const sortedSurahs = [...availableSurahs].sort((a, b) => parseInt(a) - parseInt(b));

  return (
    <div className="selector-section glass">
      <h2 className="selector-title">
        <svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round"><path d="M4 19.5v-15A2.5 2.5 2.5 0 0 1 6.5 2H20v20H6.5a2.5 2.5 2.5 0 0 1 0-5H20"/></svg>
        Pilih Surat
      </h2>
      <div className="custom-select-wrapper">
        <select 
          className="custom-select" 
          value={selectedSurah || ""} 
          onChange={(e) => onSelectSurah(e.target.value)}
        >
          <option value="" disabled>-- Pilih Surat --</option>
          {sortedSurahs.map((surahId) => {
            const idx = parseInt(surahId) - 1;
            const name = surahNames[idx] || `Surat ${surahId}`;
            return (
              <option key={surahId} value={surahId}>
                {surahId}. {name}
              </option>
            );
          })}
        </select>
      </div>
    </div>
  );
}

