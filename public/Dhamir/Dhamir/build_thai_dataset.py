def enrich_dhamir_data():
    print("Enriching dhamir_data.json and dhamir_data.js with Thai (cleaning Arabic translation)...")
    with open(os.path.join(BASE_DIR, 'th_translations.json'), 'r', encoding='utf-8') as f:
        th_trans = json.load(f)
    with open(os.path.join(BASE_DIR, 'dhamir_data.json'), 'r', encoding='utf-8') as f:
        data = json.load(f)

    for item in data:
        b = item.get('Bentuk Kata', '')
        nk = str(item.get('No kata', ''))
        g_key = f"{b}__{nk}"
        s_num = str(item.get('SURAT', ''))
        v_key = f"{item.get('SURAT')}:{item.get('AYAT')}"

        # Clean Arabic translation fields if present
        item.pop('BentukKataAR', None)
        item.pop('SuratArtiAR', None)
        item.pop('ArtiKataAR', None)
        item.pop('TeksArtiAR', None)

        # TH
        item['BentukKataTH'] = BENTUK_KATA_TH.get(b, b)
        item['SuratArtiTH'] = THAI_SURAHS.get(s_num, item.get('SuratArtiEN', ''))
        g_th = THAI_GRAMMAR.get(g_key, {})
        item['ArtiKataTH'] = g_th.get('arti_th', item.get('ArtiKataEN', ''))
        item['TeksArtiTH'] = th_trans.get(v_key, item.get('TeksArtiEN', ''))

        # Grammar dict
        if 'Grammar' not in item or not isinstance(item['Grammar'], dict):
            item['Grammar'] = {}
        item['Grammar'].pop('arti_ar', None)
        item['Grammar'].pop('desc_ar', None)
        item['Grammar'].pop('jenis_ar', None)

        if g_th.get('arti_th'): item['Grammar']['arti_th'] = g_th['arti_th']
        if g_th.get('desc_th'): item['Grammar']['desc_th'] = g_th['desc_th']
        if g_th.get('jenis_th'): item['Grammar']['jenis_th'] = g_th['jenis_th']

    with open(os.path.join(BASE_DIR, 'dhamir_data.json'), 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    js_content = f"/**\n * Dataset Dhamir & Isim Jamid Mabny Al-Qur'an 23 Bahasa\n */\nconst DHAMIR_DATA = {json.dumps(data, ensure_ascii=False, indent=2)};\n"
    with open(os.path.join(BASE_DIR, 'dhamir_data.js'), 'w', encoding='utf-8') as f:
        f.write(js_content)
    print(f"  [OK] Dhamir data enriched ({len(data)} rows).")


