def enrich_all_datasets():
    print("Enriching dhamir_data.json and dhamir_data.js with TT, UG, UZ, KU...")
    with open(os.path.join(BASE_DIR, 'tt_translations.json'), 'r', encoding='utf-8') as f:
        tt_trans = json.load(f)
    with open(os.path.join(BASE_DIR, 'ug_translations.json'), 'r', encoding='utf-8') as f:
        ug_trans = json.load(f)
    with open(os.path.join(BASE_DIR, 'uz_translations.json'), 'r', encoding='utf-8') as f:
        uz_trans = json.load(f)
    with open(os.path.join(BASE_DIR, 'ku_translations.json'), 'r', encoding='utf-8') as f:
        ku_trans = json.load(f)

    with open(os.path.join(BASE_DIR, 'dhamir_data.json'), 'r', encoding='utf-8') as f:
        dhamir_data = json.load(f)

    for item in dhamir_data:
        b = item.get('Bentuk Kata', '')
        nk = str(item.get('No kata', ''))
        g_key = f"{b}__{nk}"
        s_num = str(item.get('SURAT', ''))
        v_key = f"{item.get('SURAT')}:{item.get('AYAT')}"

        # TT
        item['BentukKataTT'] = BENTUK_KATA_TT.get(b, b)
        item['SuratArtiTT'] = TATAR_SURAHS.get(s_num, item.get('SuratArtiEN', ''))
        g_tt = TATAR_GRAMMAR.get(g_key, {})
        item['ArtiKataTT'] = g_tt.get('arti_tt', item.get('ArtiKataRU', item.get('ArtiKataEN', '')))
        item['TeksArtiTT'] = tt_trans.get(v_key, item.get('TeksArtiEN', ''))

        # UG
        item['BentukKataUG'] = BENTUK_KATA_UG.get(b, b)
        item['SuratArtiUG'] = UYGHUR_SURAHS.get(s_num, item.get('SuratArtiEN', ''))
        item['ArtiKataUG'] = item.get('ArtiKataFA', item.get('ArtiKataAR', item.get('ArtiKataEN', '')))
        item['TeksArtiUG'] = ug_trans.get(v_key, item.get('TeksArtiEN', ''))

        # UZ
        item['BentukKataUZ'] = BENTUK_KATA_UZ.get(b, b)
        item['SuratArtiUZ'] = UZBEK_SURAHS.get(s_num, item.get('SuratArtiEN', ''))
